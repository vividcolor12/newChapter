import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'out', 'interactions');
const DEST = path.join(ROOT, 'src', 'origin', 'popups');

const POPUPS = {
  'inner-0': 'ContactPopup',
  'inner-12': 'InterviewPopup',
  'inner-14': 'SketchPopup',
  'inner-23': 'GuestbookWritePopup',
  'inner-25': 'GuestbookListPopup',
  'inner-27': 'CopyAlert',
  'inner-40': 'RsvpPopup',
};

const IMG = /"https:\/\/images\.theirmood\.com\/resources\/46097\/card\/vzUGuBO4E1\/([A-Za-z0-9]+)\.(png|jpg)(\?[^"]*)?"/g;

fs.mkdirSync(DEST, { recursive: true });
for (const [id, name] of Object.entries(POPUPS)) {
  let jsx = fs.readFileSync(path.join(SRC, `${id}.popup.jsx.txt`), 'utf8')
    .replace(/ data-probe-popup="1"/g, '');
  const usesPhoto = IMG.test(jsx);
  jsx = jsx.replace(IMG, (m, pid, ext, q = '') => `{photo('${pid}', '${q}', '${ext}')}`);
  const lines = jsx.trimEnd().split('\n').map((l) => `  ${l}`).join('\n');
  const head = usesPhoto ? "import { photo } from '../../data/photos';\n\n" : '';
  const body = `// Generated by scripts/generate-popups.mjs from the reference card popup DOM.\n${head}export default function ${name}() {\n  return (\n${lines}\n  );\n}\n`;
  fs.writeFileSync(path.join(DEST, `${name}.jsx`), body);
  console.log(name, usesPhoto ? '(photo)' : '');
}
